  'room' || 'classroom' => 'Аудитория',
  'cafeteria' || 'cafe' || 'canteen' || 'food' => 'Еда',
  'atm' || 'bank' => 'Банкомат',
  'toilet' || 'restroom' || 'wc' => 'Туалет',
  'entrance' || 'exit' => 'Вход',
  'elevator' || 'lift' => 'Лифт',
  'stairs' || 'staircase' => 'Лестница',
  'escalator' => 'Эскалатор',
  'ramp' => 'Пандус',
  'library' => 'Библиотека',
  'water' || 'drinking_water' => 'Питьевая вода',
  'printer' || 'copy' => 'Печать',
  'wardrobe' || 'cloakroom' => 'Гардероб',
  'medical' || 'first_aid' => 'Медпункт',
  'vending' => 'Автомат',
